-- ============================================================================
-- Story SLE-15, SLE-17, SLE-18: Digital Wallet (Porte-monnaie électronique)
-- - Wallets table with client balance and non-negative constraint (SLE-17)
-- - Wallet transactions table for top-up reloads and purchase debits (SLE-15, SLE-18)
-- ============================================================================

CREATE TABLE IF NOT EXISTS wallets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id VARCHAR(64) NOT NULL,
    balance NUMERIC(10, 2) NOT NULL DEFAULT 0.00,
    currency VARCHAR(3) NOT NULL DEFAULT 'EUR',
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_wallets_user_id UNIQUE (user_id),
    CONSTRAINT chk_wallets_balance CHECK (balance >= 0.00)
);

CREATE TABLE IF NOT EXISTS wallet_transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    wallet_id BIGINT NOT NULL,
    user_id VARCHAR(64) NOT NULL,
    transaction_reference VARCHAR(64) NOT NULL,
    amount NUMERIC(10, 2) NOT NULL,
    type VARCHAR(32) NOT NULL,
    status VARCHAR(32) NOT NULL DEFAULT 'SUCCESS',
    payment_reference VARCHAR(128),
    store_id BIGINT,
    store_name VARCHAR(255),
    order_reference VARCHAR(64),
    description VARCHAR(255),
    balance_after NUMERIC(10, 2) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_wallet_transactions_ref UNIQUE (transaction_reference),
    CONSTRAINT chk_wallet_transactions_amount CHECK (amount > 0.00),
    CONSTRAINT fk_wallet_transactions_wallet FOREIGN KEY (wallet_id) REFERENCES wallets (id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_wallets_user_id ON wallets (user_id);
CREATE INDEX IF NOT EXISTS idx_wallet_transactions_wallet_id ON wallet_transactions (wallet_id);
CREATE INDEX IF NOT EXISTS idx_wallet_transactions_user_id ON wallet_transactions (user_id);
CREATE INDEX IF NOT EXISTS idx_wallet_transactions_created_at ON wallet_transactions (created_at DESC);
