-- Story: Generic sales transactions hierarchy with joined physical checkout specialization and item lines

-- 1. Generic parent table for all sales transactions (in-store, online, mobile, click & collect)
CREATE TABLE IF NOT EXISTS sales_transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_reference VARCHAR(64) NOT NULL,
    transaction_type VARCHAR(32) NOT NULL DEFAULT 'GENERIC',
    store_id BIGINT NOT NULL,
    client_code VARCHAR(32),
    customer_id VARCHAR(64),
    amount NUMERIC(10, 2) NOT NULL,
    currency VARCHAR(3) NOT NULL DEFAULT 'EUR',
    points_earned NUMERIC(10, 1) NOT NULL DEFAULT 0.0,
    points_rate_applied VARCHAR(128) NOT NULL,
    status VARCHAR(32) NOT NULL DEFAULT 'COMPLETED',
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_sales_transactions_ref UNIQUE (transaction_reference),
    CONSTRAINT chk_sales_transactions_amount CHECK (amount > 0),
    CONSTRAINT chk_sales_transactions_points CHECK (points_earned >= 0)
);

CREATE INDEX IF NOT EXISTS idx_sales_transactions_store_id ON sales_transactions (store_id);
CREATE INDEX IF NOT EXISTS idx_sales_transactions_client_code ON sales_transactions (client_code);
CREATE INDEX IF NOT EXISTS idx_sales_transactions_created_at ON sales_transactions (created_at);
CREATE INDEX IF NOT EXISTS idx_sales_transactions_type ON sales_transactions (transaction_type);

-- 2. Specialized sub-table for in-store physical checkout sales
CREATE TABLE IF NOT EXISTS physical_sales_transactions (
    id BIGINT PRIMARY KEY,
    merchant_id VARCHAR(64) NOT NULL,
    payment_method VARCHAR(32) NOT NULL DEFAULT 'PHYSICAL',
    CONSTRAINT fk_physical_sales_parent FOREIGN KEY (id) REFERENCES sales_transactions (id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_physical_sales_merchant_id ON physical_sales_transactions (merchant_id);

-- 3. Sub-table for purchased products / items (supports in-app purchases and future itemized physical sales)
CREATE TABLE IF NOT EXISTS sale_transaction_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_id BIGINT NOT NULL,
    product_id BIGINT,
    product_name VARCHAR(255) NOT NULL,
    unit_price NUMERIC(10, 2) NOT NULL,
    quantity INT NOT NULL,
    total_price NUMERIC(10, 2) NOT NULL,
    CONSTRAINT fk_sale_items_sale FOREIGN KEY (sale_id) REFERENCES sales_transactions (id) ON DELETE CASCADE,
    CONSTRAINT chk_sale_items_quantity CHECK (quantity > 0),
    CONSTRAINT chk_sale_items_unit_price CHECK (unit_price >= 0),
    CONSTRAINT chk_sale_items_total_price CHECK (total_price >= 0)
);

CREATE INDEX IF NOT EXISTS idx_sale_transaction_items_sale_id ON sale_transaction_items (sale_id);
